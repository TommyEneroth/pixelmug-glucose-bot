        'Å' to arrayOf("00100", "00000", "01110", "10001", "10001", "11111", "10001", "10001", "10001"),
        'Ä' to arrayOf("01010", "00000", "01110", "10001", "10001", "11111", "10001", "10001", "10001"),
        'Ö' to arrayOf("01010", "00000", "01110", "10001", "10001", "10001", "10001", "10001", "01110"),
        '-' to arrayOf("00000", "00000", "00000", "11111", "00000", "00000", "00000"),
        '.' to arrayOf("00", "00", "00", "00", "00", "11", "11"),
        '!' to arrayOf("1", "1", "1", "1", "1", "0", "1"),
        ':' to arrayOf("00", "11", "11", "00", "11", "11", "00"),
        '~' to arrayOf("00000", "00000", "01001", "10110", "00000", "00000", "00000"),
        ' ' to arrayOf("000", "000", "000", "000", "000", "000", "000"),
        '↗' to arrayOf("00111", "00011", "00101", "01000", "10000", "00000", "00000"),
        '↘' to arrayOf("10000", "01000", "00101", "00011", "00111", "00000", "00000"),
        '→' to arrayOf("00000", "00100", "00010", "11111", "00010", "00100", "00000"),
    )

    /** Uppercase (keeps Å Ä Ö); fold en-dash so the font can render it. */
    fun normalize(s: String): String = s.uppercase().replace('–', '-')

    fun width(s: String): Int {
        var w = 0
        for (i in s.indices) w += (G[s[i]]?.get(0)?.length ?: 3) + if (i < s.length - 1) 1 else 0
        return w
    }

    /** Draw `s` bottom-aligned within GLYPH_H at (x,y) into a W*Hgrid, colour `idx`. */
    fun draw(f: ByteArray, x: Int, y: Int, s: String, idx: Int, gw: Int, gh: Int) {
        var cx = x
        for (ch in s) {
            val g = G[ch]
            if (g == null) { cx += (G[' ']!![0].length) + 1; continue }
            val w = g[0].length
            val top = y + H - g.size // bottom-align (negative for 9-row accents)
            for (r in g.indices) for (c in 0 until w)
                if (g[r][c] == '1') {
                    val px = cx + c; val py = top + r
                    if (px in 0 until gw && py in 0 until gh) f[py * gw + px] = idx.toByte()
                }
            cx += w + 1
        }
    }
}
