package se.pixelmug.glucoseface

/** 5x7 pixel font (Å/Ä/Ö are 9-row; drawn bottom-aligned so marks rise above). */
object Font {
    const val H = 7

    private val G: Map<Char, Array<String>> = mapOf(
        '0' to arrayOf("01110", "10001", "10011", "10101", "11001", "10001", "01110"),
        '1' to arrayOf("00100", "01100", "00100", "00100", "00100", "00100", "01110"),
        '2' to arrayOf("01110", "10001", "00001", "00110", "01000", "10000", "11111"),
